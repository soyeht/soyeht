#!/usr/bin/env python3
"""Write and check the third-party notices that every Soyeht package ships (ADR 0149).

    third_party_notices.py generate        write THIRD-PARTY-NOTICES.txt
    third_party_notices.py check           fail when it is stale or a dependency is not allowed
    third_party_notices.py refresh-swift --checkouts DIR
                                           renew scripts/third_party/swift.json and its texts

The file lists the Rust crates of the three cargo workspaces (`engine`, `apps/desktop`,
`apps/android`), the Swift packages pinned by the `Package.resolved` files, the Gradle libraries of
the Android app and the fonts and icons shipped as files, then the license and notice texts, each
once. A dependency whose license is outside `scripts/third_party/policy.json` fails both commands;
the policy's `exceptions` hold the known ones, each with its reason, and an exception nobody uses
fails too. Packages take the file with `notices_file()` (the packaging scripts)."""

from __future__ import annotations

import argparse
import difflib
import json
import shutil
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path

import third_party_licenses as licenses
import third_party_sources as sources

ROOT = sources.ROOT
OUTPUT = ROOT / "THIRD-PARTY-NOTICES.txt"
WIDTH = 100
HEADING = """\
Soyeht third-party notices
==========================

Soyeht is licensed under the Apache License 2.0 (LICENSE, NOTICE). It is built with the
open-source components below. Each keeps its own license, whose text follows the list, once for
every distinct text. Where a component offers a choice of licenses, the one named in the list is
the one Soyeht follows.

This file is generated by scripts/third_party_notices.py from the Cargo.lock files of engine/,
apps/desktop/ and apps/android/, the Package.resolved files of the Swift packages,
apps/android/app/build.gradle.kts and scripts/third_party/. Do not edit it:
    uv run python scripts/third_party_notices.py generate
"""
SECTIONS = (
    ("Rust", "Rust crates"),
    ("Swift", "Swift packages"),
    ("Android", "Android libraries"),
    ("Asset", "Fonts and icons"),
)


def collect(policy, root=ROOT, metadata=sources.cargo_metadata):
    """Every component of every source. Raises `sources.SourceError` for a dependency that is not
    allowed or described, or for an exception nothing uses."""
    found = (
        sources.cargo_components(policy, root, metadata=metadata)
        + sources.swift_components(policy, root)
        + sources.gradle_components(policy, root)
        + sources.asset_components(policy, root)
    )
    used = {(c.name, c.license) for c in found if c.exception}
    unused = sorted(set(policy.exceptions) - used)
    if unused:
        raise sources.SourceError(f"policy.json has exceptions that no dependency needs: {unused}")
    return found


def wrapped(prefix, words, indent="    "):
    return textwrap.fill(", ".join(words), WIDTH, initial_indent=prefix, subsequent_indent=indent,
                         break_long_words=False, break_on_hyphens=False)


def render(components):
    """The notices file for these components (a pure function: same input, same bytes)."""
    lines = [HEADING]
    lines.append(f"1. Components ({len(components)})\n")
    for ecosystem, title in SECTIONS:
        group = sorted((c for c in components if c.ecosystem == ecosystem), key=lambda c: (c.name.lower(), c.version))
        if not group:
            continue
        lines.append(f"{title} ({len(group)})")
        for component in group:
            built = f"  [{', '.join(sorted(component.products))}]" if component.products else ""
            lines.append(f"  {component.name} {component.version}".rstrip() + f"  ({component.license}){built}")
            if component.url:
                lines.append(f"      {component.url}")
            lines += [f"      {line}" for line in component.copyright]
        lines.append("")
    lines.append("2. License and notice texts\n")
    blocks = {}
    for component in components:
        for text in component.texts:
            key = " ".join(text.body.split())
            block = blocks.setdefault(key, {"label": text.label, "body": text.body, "users": set()})
            block["users"].add(f"{component.name} {component.version}".rstrip())
    ordered = sorted(blocks.values(), key=lambda b: (b["label"], b["body"]))
    for number, block in enumerate(ordered, 1):
        lines.append("-" * WIDTH)
        lines.append(f"Text {number} of {len(ordered)}: {block['label']}")
        lines.append(wrapped("Used by: ", sorted(block["users"], key=str.lower)))
        lines.append("-" * WIDTH)
        lines.append(block["body"])
    return "\n".join(lines).rstrip("\n") + "\n"


def notices_file():
    """The path of the generated file, for a packaging script; it must exist."""
    if not OUTPUT.is_file():
        raise sources.SourceError(f"{OUTPUT.name} is missing: run scripts/third_party_notices.py generate")
    return OUTPUT


def refresh_swift(checkouts, policy, root=ROOT):
    """Renew `swift.json` and the texts under `scripts/third_party/swift/` from a folder that holds
    one checkout per Swift package (named by its identity or its repository), at the revision the
    Package.resolved files pin. A checkout at another revision is fetched into a temporary folder."""
    pins = sources.resolved_pins(root)
    recorded = {}
    sources.SWIFT_TEXTS.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as scratch:
        for identity, (version, revision, location) in sorted(pins.items()):
            folder = locate(Path(checkouts), identity, location, revision, Path(scratch))
            files = {}
            for path in sorted(folder.rglob("*")):
                relative = path.relative_to(folder)
                if _vendored_license(relative) and path.is_file():
                    files[relative.as_posix()] = licenses.normal(path.read_text(errors="replace"))
            top = [n for n in files if "/" not in n and not licenses.is_notice_file(n)]
            if not top:
                raise sources.SourceError(f"{identity} has no license file at its top")
            kind = policy.clarify.get(identity, {}).get("license") or licenses.classify(files[sorted(top)[0]])
            if not kind:
                raise sources.SourceError(f"{identity}: {sorted(top)[0]} is not a license text I know: describe it")
            target = sources.SWIFT_TEXTS / identity
            shutil.rmtree(target, ignore_errors=True)
            for relative, body in files.items():
                (target / relative).parent.mkdir(parents=True, exist_ok=True)
                (target / relative).write_text(body)
            recorded[identity] = {"revision": revision, "license": kind, "files": sorted(files)}
    sources.SWIFT_DATA.write_text(json.dumps({"packages": recorded}, indent=2, sort_keys=True) + "\n")


def _vendored_license(relative):
    parts = relative.parts
    skipped = {"Tests", "Docs", "docs", "Examples", ".git", ".build", "Benchmarks", "node_modules"}
    return len(parts) <= 5 and not skipped & set(parts) and licenses.is_license_file(parts[-1])


def locate(checkouts, identity, location, revision, scratch):
    """A folder with the package at `revision`: a checkout that already is there, or a fetch."""
    for candidate in (checkouts / identity, checkouts / location.rstrip("/").removesuffix(".git").split("/")[-1]):
        if candidate.is_dir():
            head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=candidate, capture_output=True, text=True)
            if head.stdout.strip() == revision:
                return candidate
    target = scratch / identity
    target.mkdir()
    for command in (["init", "-q"], ["fetch", "-q", "--depth", "1", location, revision], ["checkout", "-q", "FETCH_HEAD"]):
        done = subprocess.run(["git", *command], cwd=target, capture_output=True, text=True)
        if done.returncode:
            raise sources.SourceError(f"git {command[0]} for {identity} failed: {done.stderr.strip()[-300:]}")
    return target


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("command", choices=("generate", "check", "refresh-swift"))
    parser.add_argument("--checkouts", help="refresh-swift: a folder of Swift package checkouts")
    arguments = parser.parse_args(argv)
    try:
        if arguments.command == "refresh-swift":
            refresh_swift(arguments.checkouts or tempfile.gettempdir(), licenses.load_policy())
            return 0
        components = collect(licenses.load_policy())
        for component in sorted((c for c in components if c.exception), key=lambda c: c.name):
            print(f"warning: {component.name} {component.version} is {component.license}, outside the "
                  f"allow-list: {component.exception}", file=sys.stderr)
        text = render(components)
        if arguments.command == "generate":
            OUTPUT.write_text(text)
            print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(text)} bytes)")
            return 0
        current = OUTPUT.read_text() if OUTPUT.is_file() else ""
        if current != text:
            diff = difflib.unified_diff(current.splitlines(), text.splitlines(), "committed", "generated", lineterm="", n=0)
            print("\n".join(list(diff)[:40]), file=sys.stderr)
            print("third-party notices are stale: uv run python scripts/third_party_notices.py generate", file=sys.stderr)
            return 1
        print("third-party notices: ok")
        return 0
    except (sources.SourceError, licenses.LicenseError) as error:
        print(f"third-party notices: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
