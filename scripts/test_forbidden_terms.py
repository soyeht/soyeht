import contextlib
import io
import unittest

from forbidden_terms import matches, parse_terms, scan, scan_message


class VocabularyTests(unittest.TestCase):
    def test_case_punctuation_and_pair_across_lines_are_rejected(self):
        restricted = {"sampleword", "sample pair"}
        for text in ("SAMPLEWORD", "(sampleword)", "sample\npair", "sample_pair"):
            with self.subTest(text=text):
                self.assertTrue(matches(text, restricted))

    def test_substring_is_not_a_token(self):
        self.assertFalse(matches("samplewordlong sample different pair", {"sampleword", "sample pair"}))

    def test_red_control_and_clean_control_use_same_rule(self):
        restricted = {"sampleword"}
        self.assertFalse(matches("allowed words", restricted))
        self.assertTrue(matches("allowed sampleword words", restricted))

    def test_policy_fails_closed(self):
        for policy in ("", "\n\t "):
            with self.subTest(policy=policy), self.assertRaises(ValueError):
                parse_terms(policy)
        self.assertEqual(parse_terms("SAMPLEWORD\n sample pair \n"), {"sampleword", "sample pair"})

    def test_utf16_and_diagnostics_do_not_expose_term(self):
        output = io.StringIO()
        with contextlib.redirect_stderr(output):
            self.assertTrue(scan("fixture", "sampleword".encode("utf-16"), {"sampleword"}))
        self.assertEqual(output.getvalue(), "fixture:1\n")
        self.assertFalse(scan("fixture", b"\0\1\2", {"sampleword"}))

    def test_message_policy_is_separate_and_case_insensitive(self):
        for phrase in ("Co-Authored-By", "Generated By", "CLAUDE", "CODEX", "OPENAI", "ANTHROPIC"):
            output = io.StringIO()
            with contextlib.redirect_stderr(output):
                self.assertTrue(scan_message("commit", "fix: change\n" + phrase))
            self.assertEqual(output.getvalue(), "commit:2\n")
        self.assertFalse(scan_message("commit", "feat(protocol): define message types"))


if __name__ == "__main__":
    unittest.main()
