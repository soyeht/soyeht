class VocabularyTests(unittest.TestCase):
    def test_case_punctuation_and_pair_across_lines_are_rejected(self):
        restricted = {"sampleword", "sample pair"}
        for text in ("SAMPLEWORD", "(sampleword)", "sample\npair", "sample_pair"):
            with self.subTest(text=text):
                self.assertTrue(matches(text, restricted))

    def test_substring_is_not_a_token(self):
        self.assertFalse(matches("samplewordlong sample different pair", {"sampleword", "sample pair"}))

    def test_red_control_and_clean_control_use_same_rule(self):
        restricted = {"sampleword"}
        self.assertFalse(matches("allowed words", restricted))
        self.assertTrue(matches("allowed sampleword words", restricted))

    def test_policy_fails_closed(self):
        for policy in ("", "\n\t "):
            with self.subTest(policy=policy), self.assertRaises(ValueError):
                parse_terms(policy)
        self.assertEqual(parse_terms("SAMPLEWORD\n sample pair \n"), {"sampleword", "sample pair"})

    def test_utf16_and_diagnostics_do_not_expose_term(self):
        output = io.StringIO()
        with contextlib.redirect_stderr(output):
            self.assertTrue(scan("fixture", "sampleword".encode("utf-16"), {"sampleword"}))
        self.assertEqual(output.getvalue(), "fixture:1\n")
        self.assertFalse(scan("fixture", b"\0\1\2", {"sampleword"}))

    def test_message_policy_is_separate_and_case_insensitive(self):
        for phrase in ("Co-Authored-By", "Generated By", "CLAUDE", "CODEX", "OPENAI", "ANTHROPIC"):
            output = io.StringIO()
            with contextlib.redirect_stderr(output):
                self.assertTrue(scan_message("commit", "fix: change\n" + phrase))
            self.assertEqual(output.getvalue(), "commit:2\n")
        self.assertFalse(scan_message("commit", "feat(protocol): define message types"))


class SkipTests(unittest.TestCase):
    def test_only_the_flag_with_no_vocabulary_skips(self):
        self.assertTrue(skipping({SKIP_ENV: "1"}))
        self.assertTrue(skipping({SKIP_ENV: "1", "FORBIDDEN_TERMS": " \n"}))
        self.assertFalse(skipping({}))
        self.assertFalse(skipping({SKIP_ENV: "0"}))
        self.assertFalse(skipping({SKIP_ENV: "yes"}))

    def test_supplied_terms_always_win_over_the_flag(self):
        self.assertFalse(skipping({SKIP_ENV: "1", "FORBIDDEN_TERMS": "sampleword"}))

    def test_a_skipped_run_says_so_loudly_and_still_runs(self):
        errors = io.StringIO()
        output = io.StringIO()
        with (mock.patch.dict(os.environ, {SKIP_ENV: "1", "FORBIDDEN_TERMS": ""}),
              mock.patch.object(sys, "argv", ["forbidden_terms.py"]),
              contextlib.redirect_stderr(errors), contextlib.redirect_stdout(output)):
            self.assertEqual(main(), 0)
        self.assertIn("SKIPPED", errors.getvalue())
        self.assertIn("SKIPPED", output.getvalue())

    def test_without_the_flag_a_missing_vocabulary_still_fails(self):
        with mock.patch.dict(os.environ, {"FORBIDDEN_TERMS": ""}, clear=False):
            os.environ.pop(SKIP_ENV, None)
            with mock.patch.object(sys, "argv", ["forbidden_terms.py"]), self.assertRaises(ValueError):
                main()


def run_main(*arguments, environ=None, stdin=None):
    """main() with a prepared environment; returns (exit code, stdout, stderr)."""
    output, errors = io.StringIO(), io.StringIO()
    environment = {"FORBIDDEN_TERMS": "", **(environ or {})}
    with (mock.patch.dict(os.environ, environment),
          mock.patch.object(sys, "argv", ["forbidden_terms.py", *arguments]),
          contextlib.redirect_stdout(output), contextlib.redirect_stderr(errors)):
        if stdin is not None:
            with mock.patch.object(sys, "stdin", mock.Mock(buffer=io.BytesIO(stdin.encode()))):
                code = main()
        else:
            code = main()
    return code, output.getvalue(), errors.getvalue()


class TextFileTests(unittest.TestCase):
    """A pull request title and body are scanned before `gh pr create`."""

    def write(self, text):
        directory = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, directory, ignore_errors=True)
        path = Path(directory) / "pr.md"
        path.write_text(text)
        return str(path)

    def test_attribution_in_the_text_fails_without_any_vocabulary(self):
        path = self.write("Title\n\nGenerated by a tool\n")
        code, _, errors = run_main("--messages-only", "--text-file", path)
        self.assertEqual(code, 1)
        self.assertEqual(errors, f"{path}:3\n")

    def test_clean_text_passes_without_any_vocabulary(self):
        code, output, _ = run_main("--messages-only", "--text-file", self.write("Add the precheck\n"))
        self.assertEqual(code, 0)
        self.assertIn("no vocabulary", output)

    def test_the_vocabulary_is_used_when_supplied_and_never_printed(self):
        path = self.write("Title\nmentions sampleword here\n")
        code, _, errors = run_main("--messages-only", "--text-file", path,
                                   environ={"FORBIDDEN_TERMS": "sampleword"})
        self.assertEqual(code, 1)
        self.assertEqual(errors, f"{path}:2\n")

    def test_standard_input_is_read_for_a_dash(self):
        code, _, errors = run_main("--messages-only", "--text-file", "-", stdin="fine\nCo-Authored-By: x\n")
        self.assertEqual(code, 1)
        self.assertEqual(errors, "stdin:2\n")
        self.assertEqual(run_main("--messages-only", "--text-file", "-", stdin="fine\n")[0], 0)

    def test_the_full_scan_checks_the_text_too(self):
        code, _, errors = run_main("--text-file", self.write("openai\n"),
                                   environ={SKIP_ENV: "1"})
        self.assertEqual(code, 1)
        self.assertIn(":1", errors)

    def test_a_missing_file_is_an_error_not_a_pass(self):
        with self.assertRaises(OSError):
            run_main("--messages-only", "--text-file", "/nonexistent/pr.md")


class MessagesOnlyTests(unittest.TestCase):
    BASE = "a" * 40

    def history(self, messages):
        def fake(*args):
            if args[0] == "rev-list":
                return "\n".join(f"rev{i}" for i in range(len(messages))).encode()
            if args[0] == "show":
                return messages[int(args[-1][3:])].encode()
            raise AssertionError(f"messages-only must not run git {args[0]}")
        return mock.patch("forbidden_terms.git", side_effect=fake)

    def test_a_commit_message_with_attribution_fails_and_names_the_commit(self):
        with self.history(["fine", "feat: x\n\nCo-authored-by: someone"]):
            code, _, errors = run_main("--messages-only", "--base", self.BASE)
        self.assertEqual(code, 1)
        self.assertEqual(errors, "commit rev1:3\n")

    def test_clean_messages_pass_and_the_tree_is_not_read(self):
        with self.history(["fine", "also fine"]):
            code, output, _ = run_main("--messages-only", "--base", self.BASE,
                                       environ={"FORBIDDEN_TERMS": "sampleword"})
        self.assertEqual(code, 0)
        self.assertIn("clean", output)

    def test_it_needs_something_to_scan(self):
        with self.assertRaises(SystemExit):
            with contextlib.redirect_stderr(io.StringIO()):
                run_main("--messages-only")


