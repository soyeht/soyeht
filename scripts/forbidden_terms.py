#!/usr/bin/env python3
"""Check repository text without keeping or printing restricted vocabulary."""
import argparse
import os
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MESSAGE_PATTERNS = ("co-authored-by", "generated by", "claude", "codex", "openai", "anthropic")


def git(*args):
    return subprocess.check_output(["git", *args], cwd=ROOT)


def parse_terms(text):
    terms = {line.strip().lower() for line in text.splitlines() if line.strip()}
    if not terms:
        raise ValueError("FORBIDDEN_TERMS is missing or empty")
    return terms


def matches(text, forbidden):
    # Underscores, punctuation and newlines cannot hide adjacent words.
    words = list(re.finditer(r"[^\W_]+", text.lower()))
    candidates = [(word.group(), word.start()) for word in words]
    candidates.extend((a.group() + " " + b.group(), a.start())
                      for a, b in zip(words, words[1:]))
    # Also cover single names containing punctuation, without a cleartext list.
    candidates.extend((word.group(), word.start())
                      for word in re.finditer(r"[\w.-]+", text.lower()))
    hits = set()
    for value, offset in candidates:
        if value in forbidden:
            hits.add(text.count("\n", 0, offset) + 1)
    return sorted(hits)


def scan(label, raw, forbidden):
    if b"\0" in raw:
        # UTF-16/32 text must not disappear as a binary file.
        if raw.startswith((b"\xff\xfe\0\0", b"\0\0\xfe\xff")):
            text = raw.decode("utf-32")
        elif raw.startswith((b"\xff\xfe", b"\xfe\xff")):
            text = raw.decode("utf-16")
        else:
            return False
    else:
        # Preserve ASCII words even in legacy text encodings.
        text = raw.decode("utf-8", errors="replace")
    found = matches(text, forbidden)
    for line in found:
        print(f"{label}:{line}", file=sys.stderr)
    return bool(found)


def scan_message(label, text):
    failed = False
    for number, line in enumerate(text.splitlines(), 1):
        if any(pattern in line.lower() for pattern in MESSAGE_PATTERNS):
            print(f"{label}:{number}", file=sys.stderr)
            failed = True
    return failed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", help="Full base commit OID for a pull request")
    parser.add_argument("--event-file", type=Path)
    args = parser.parse_args()
    forbidden = parse_terms(os.environ.get("FORBIDDEN_TERMS", ""))
    failed = False
    if args.base:
        if not re.fullmatch(r"[0-9a-f]{40}", args.base):
            parser.error("--base must be a full commit OID")
        revisions = git("rev-list", f"{args.base}..HEAD").decode().splitlines()
        seen = set()
        for rev in revisions:
            message = git("show", "-s", "--format=%B", rev)
            failed |= scan(f"commit {rev}", message, forbidden)
            failed |= scan_message(f"commit {rev}", message.decode(errors="replace"))
            for entry in git("ls-tree", "-rz", rev).split(b"\0"):
                if not entry:
                    continue
                metadata, path = entry.split(b"\t", 1)
                mode, kind, oid = metadata.split()
                if kind != b"blob" or oid in seen:
                    continue
                seen.add(oid)
                failed |= scan(f"{rev}:{path.decode(errors='replace')}",
                               git("cat-file", "blob", oid.decode()), forbidden)
    # Local runs include untracked, non-ignored work, before authorship.
    for name in git("ls-files", "-z", "--cached", "--others", "--exclude-standard").split(b"\0"):
        if not name:
            continue
        path = ROOT / name.decode()
        if path.is_symlink():
            raw = str(path.readlink()).encode()
        elif path.is_file():
            raw = path.read_bytes()
        else:
            continue
        failed |= scan(str(path.relative_to(ROOT)), raw, forbidden)
    if args.event_file:
        event = json.loads(args.event_file.read_text())
        pr = event.get("pull_request", {})
        failed |= scan("PR title/body", (pr.get("title", "") + "\n" +
                                        (pr.get("body") or "")).encode(), forbidden)
        failed |= scan_message("PR body", pr.get("body") or "")
    if failed:
        return 1
    print("forbidden-terms: clean")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        print(f"forbidden-terms: {error}", file=sys.stderr)
        sys.exit(1)
