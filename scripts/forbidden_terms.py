#!/usr/bin/env python3
"""Check repository text without keeping or printing restricted vocabulary."""
import argparse
import os
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ZERO_OID = "0" * 40
MESSAGE_PATTERNS = ("co-authored-by", "generated by", "claude", "codex", "openai", "anthropic")
# A contributor without the maintainers' vocabulary sets this to 1 to run everything else.
SKIP_ENV = "SOYEHT_SKIP_FORBIDDEN_TERMS"
SKIP_BANNER = (
    "forbidden-terms: ################################################################\n"
    "forbidden-terms: SKIPPED: the restricted-vocabulary scan did not run ({reason}).\n"
    "forbidden-terms: Commit messages and PR text are still checked for AI attribution.\n"
    "forbidden-terms: A maintainer runs the full scan before the merge.\n"
    "forbidden-terms: ################################################################"
)
# Where the maintainers' vocabulary comes from when FORBIDDEN_TERMS is not set: the file named
# by this git setting, else the default path. It never lives in the repository.
VOCABULARY_FILE_KEY = "soyeht.vocabularyFile"
DEFAULT_VOCABULARY_FILE = "~/.config/soyeht/forbidden-terms.txt"
# `git config --bool soyeht.requireVocabulary true` makes a missing vocabulary an error.
REQUIRE_KEY = "soyeht.requireVocabulary"
NO_VOCABULARY_NOTICE = ("forbidden-terms: no restricted vocabulary found (FORBIDDEN_TERMS or the "
                        "vocabulary file); only AI attribution was checked. See CONTRIBUTING.md.")


class VocabularyMissing(ValueError):
    """The vocabulary is required (`soyeht.requireVocabulary`) and none was found."""


class GitConfigError(ValueError):
    """`git config` could not answer (a malformed setting): never read as "unset"."""


def git(*args):
    return subprocess.check_output(["git", *args], cwd=ROOT)


def git_config(*args):
    """The output of `git config ARGS` in this repository, or None when the key is not set.

    Exit 1 means unset. Any other failure (exit 128 for a malformed boolean such as `ture`) is an
    error, so a mistyped `soyeht.requireVocabulary` cannot turn the check off."""
    result = subprocess.run(["git", "config", *args], cwd=ROOT, capture_output=True, text=True)
    if result.returncode == 0:
        return result.stdout.strip()
    if result.returncode == 1:
        return None
    raise GitConfigError(f"`git config {' '.join(args)}` failed (exit {result.returncode}); "
                         "is the setting malformed?")


def vocabulary_file(environ, config):
    """The path of the vocabulary file: the git setting, else the default, `~` expanded."""
    path = config("--get", VOCABULARY_FILE_KEY) or DEFAULT_VOCABULARY_FILE
    if path == "~" or path.startswith(("~/", "~\\")):
        home = environ.get("HOME") or environ.get("USERPROFILE") or str(Path.home())
        path = str(Path(home) / path[2:])
    return Path(path)


def find_vocabulary(environ, config=None):
    """(where the terms came from, the terms): "env", "file" or "none".

    One lookup for the hook, the precheck and the gate: `FORBIDDEN_TERMS` first, else the file
    named by `git config soyeht.vocabularyFile`, else `~/.config/soyeht/forbidden-terms.txt`.
    With `git config --bool soyeht.requireVocabulary` true, no vocabulary raises
    `VocabularyMissing` (fail closed). The terms are returned to the caller and never printed."""
    config = config or git_config
    terms = parse_optional_terms(environ.get("FORBIDDEN_TERMS", ""))
    if terms:
        return "env", terms
    try:
        terms = parse_optional_terms(vocabulary_file(environ, config).read_text(errors="replace"))
    except FileNotFoundError:
        terms = set()
    if terms:
        return "file", terms
    if config("--bool", "--get", REQUIRE_KEY) == "true":
        raise VocabularyMissing(
            "no restricted vocabulary: set FORBIDDEN_TERMS or put the list in the file named by "
            f"`git config {VOCABULARY_FILE_KEY}` (default {DEFAULT_VOCABULARY_FILE}); "
            f"`{REQUIRE_KEY}` is true")
    return "none", terms


def load_vocabulary(environ, config=None):
    """The restricted terms, or an empty set when none is available (see `find_vocabulary`)."""
    return find_vocabulary(environ, config)[1]


def parse_optional_terms(text):
    """The vocabulary when one is supplied, else nothing: the message patterns still apply."""
    return {line.strip().lower() for line in text.splitlines() if line.strip()}


def skipping(environ):
    """True when the vocabulary is absent and the caller asked to go on without it.

    Supplied terms always win: the flag never turns a real scan off."""
    return not environ.get("FORBIDDEN_TERMS", "").strip() and environ.get(SKIP_ENV) == "1"


def matches(text, forbidden):
    # Underscores, punctuation and newlines cannot hide adjacent words.
    words = list(re.finditer(r"[^\W_]+", text.lower()))
    candidates = [(word.group(), word.start()) for word in words]
    candidates.extend((a.group() + " " + b.group(), a.start())
                      for a, b in zip(words, words[1:]))
    # Also cover single names containing punctuation, without a cleartext list.
    candidates.extend((word.group(), word.start())
                      for word in re.finditer(r"[\w.-]+", text.lower()))
    hits = set()
    for value, offset in candidates:
        if value in forbidden:
            hits.add(text.count("\n", 0, offset) + 1)
    return sorted(hits)


def scan(label, raw, forbidden):
    if b"\0" in raw:
        # UTF-16/32 text must not disappear as a binary file.
        if raw.startswith((b"\xff\xfe\0\0", b"\0\0\xfe\xff")):
            text = raw.decode("utf-32")
        elif raw.startswith((b"\xff\xfe", b"\xfe\xff")):
            text = raw.decode("utf-16")
        else:
            return False
    else:
        # Preserve ASCII words even in legacy text encodings.
        text = raw.decode("utf-8", errors="replace")
    found = matches(text, forbidden)
    for line in found:
        print(f"{label}:{line}", file=sys.stderr)
    return bool(found)


def scan_message(label, text):
    failed = False
    for number, line in enumerate(text.splitlines(), 1):
        if any(pattern in line.lower() for pattern in MESSAGE_PATTERNS):
            print(f"{label}:{number}", file=sys.stderr)
            failed = True
    return failed


HUNK = re.compile(r"@@ -\d+(?:,(\d+))? \+(\d+)(?:,(\d+))? @@")


def added_lines(diff):
    """{path: [(line number in the new file, text)]} for the added lines of a `-U0` diff.

    The hunk header says how many lines follow, so an added line that reads `++ x` is not
    taken for a file header."""
    found, path, number, old_left, new_left = {}, None, 0, 0, 0
    for raw in diff.split(b"\n"):
        line = raw.decode(errors="replace")
        if old_left or new_left:
            if line.startswith("+"):
                found.setdefault(path, []).append((number, line[1:]))
                number += 1
                new_left -= 1
            elif line.startswith("-"):
                old_left -= 1
        elif line.startswith("+++ "):
            path = line[6:] if line.startswith("+++ b/") else None
        elif hunk := HUNK.match(line):
            old_left = int(hunk[1]) if hunk[1] is not None else 1
            number = int(hunk[2])
            new_left = int(hunk[3]) if hunk[3] is not None else 1
    return found


def scan_added(label, lines, forbidden):
    """Scan the added lines of one file; report the line numbers of the new file."""
    text = "\n".join(line for _, line in lines)
    found = [lines[index - 1][0] for index in matches(text, forbidden)]
    for number in sorted(set(found)):
        print(f"{label}:{number}", file=sys.stderr)
    return bool(found)


def has_commit(oid):
    """Whether this clone has the commit `oid` (the all-zero id of a new ref never exists)."""
    if oid == ZERO_OID:
        return False
    try:
        git("cat-file", "-e", f"{oid}^{{commit}}")
    except subprocess.CalledProcessError:
        return False
    return True


def pushed_revisions(updates, remote):
    """Commits the push adds: each updated ref's new tip, minus what the remote already has."""
    revisions = []
    for update in updates:
        fields = update.split()
        if len(fields) != 4 or fields[1] == ZERO_OID:  # a deletion pushes no commit
            continue
        local, remote_oid = fields[1], fields[3]
        # A new branch, or a force-push over a commit this clone does not have (rev-list would
        # die on it): everything the remote's tracking refs do not reach.
        exclude = [remote_oid] if has_commit(remote_oid) else (
            [f"--remotes={remote}"] if remote else [])
        for rev in git("rev-list", local, "--not", *exclude).decode().split():
            if rev not in revisions:
                revisions.append(rev)
    return revisions


def scan_push(updates, remote, forbidden):
    """Messages and added lines of the commits a push sends. True when something was found."""
    failed = False
    for rev in pushed_revisions(updates, remote):
        message = git("show", "-s", "--format=%B", rev)
        failed |= scan(f"commit {rev}", message, forbidden)
        failed |= scan_message(f"commit {rev}", message.decode(errors="replace"))
        if not forbidden:
            continue
        diff = git("-c", "core.quotepath=off", "show", "--format=", "-U0", "--no-renames",
                   "--no-color", "--no-ext-diff", "--diff-merges=first-parent", rev)
        for path, lines in added_lines(diff).items():
            failed |= scan_added(f"{rev[:12]}:{path}", lines, forbidden)
    return failed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", help="Full base commit OID for a pull request")
    parser.add_argument("--event-file", type=Path)
    parser.add_argument("--text-file", type=Path, action="append", default=[], metavar="PATH",
                        help="a pull request title and body (or any text) to scan before "
                             "`gh pr create`; `-` reads standard input. May be repeated.")
    parser.add_argument("--messages-only", action="store_true",
                        help="scan only the commit messages of --base..HEAD and the text files, "
                             "not the tree: cheap enough for a hook, and it needs no vocabulary "
                             "(the terms are used when FORBIDDEN_TERMS is set)")
    parser.add_argument("--pre-push", metavar="REMOTE", nargs="?", const="",
                        help="read the pre-push hook's standard input (one ref update per line) "
                             "and scan the messages and the added lines of the commits being "
                             "pushed; REMOTE is the hook's first argument")
    parser.add_argument("--print-source", action="store_true",
                        help="print where the vocabulary comes from (env, file or none), never "
                             "the terms; `check_all.sh` uses it to tell a real list from none")
    args = parser.parse_args()
    if args.print_source:
        print(find_vocabulary(os.environ)[0])
        return 0
    # One lookup for every mode: FORBIDDEN_TERMS, else the vocabulary file (fail closed when
    # `soyeht.requireVocabulary` is true and there is none).
    forbidden = load_vocabulary(os.environ)
    if args.pre_push is not None:
        if not forbidden:
            print(NO_VOCABULARY_NOTICE, file=sys.stderr)
        failed = scan_push(sys.stdin.buffer.read().decode(errors="replace").splitlines(), args.pre_push, forbidden)
        if failed:
            return 1
        print("forbidden-terms: push clean" + ("" if forbidden else " (attribution patterns only)"))
        return 0
    if args.messages_only:
        if not args.base and not args.text_file:
            parser.error("--messages-only needs --base or --text-file")
        skip = False
    else:
        skip = skipping(os.environ) and not forbidden
        if not skip and not forbidden:
            raise ValueError("FORBIDDEN_TERMS is missing or empty")
    if skip:
        print(SKIP_BANNER.format(reason=f"{SKIP_ENV}=1 and no FORBIDDEN_TERMS"), file=sys.stderr)
    failed = False
    if args.base:
        if not re.fullmatch(r"[0-9a-f]{40}", args.base):
            parser.error("--base must be a full commit OID")
        revisions = git("rev-list", f"{args.base}..HEAD").decode().splitlines()
        seen = set()
        for rev in revisions:
            message = git("show", "-s", "--format=%B", rev)
            failed |= scan(f"commit {rev}", message, forbidden)
            failed |= scan_message(f"commit {rev}", message.decode(errors="replace"))
            # With no vocabulary there is nothing to look for in the files of the history.
            scan_files = forbidden and not args.messages_only
            for entry in git("ls-tree", "-rz", rev).split(b"\0") if scan_files else ():
                if not entry:
                    continue
                metadata, path = entry.split(b"\t", 1)
                mode, kind, oid = metadata.split()
                if kind != b"blob" or oid in seen:
                    continue
                seen.add(oid)
                failed |= scan(f"{rev}:{path.decode(errors='replace')}",
                               git("cat-file", "blob", oid.decode()), forbidden)
    # Local runs include untracked, non-ignored work, before authorship.
    tree = () if args.messages_only else git(
        "ls-files", "-z", "--cached", "--others", "--exclude-standard").split(b"\0")
    for name in tree if forbidden else ():
        if not name:
            continue
        path = ROOT / name.decode()
        if path.is_symlink():
            raw = str(path.readlink()).encode()
        elif path.is_file():
            raw = path.read_bytes()
        else:
            continue
        failed |= scan(str(path.relative_to(ROOT)), raw, forbidden)
    for text_file in args.text_file:
        raw = sys.stdin.buffer.read() if str(text_file) == "-" else text_file.read_bytes()
        label = "stdin" if str(text_file) == "-" else str(text_file)
        failed |= scan(label, raw, forbidden)
        failed |= scan_message(label, raw.decode(errors="replace"))
    if args.event_file:
        event = json.loads(args.event_file.read_text())
        pr = event.get("pull_request", {})
        failed |= scan("PR title/body", (pr.get("title", "") + "\n" +
                                        (pr.get("body") or "")).encode(), forbidden)
        failed |= scan_message("PR body", pr.get("body") or "")
    if failed:
        return 1
    if skip:
        print("forbidden-terms: clean (vocabulary scan SKIPPED)")
    elif args.messages_only and not forbidden:
        print("forbidden-terms: messages clean (no vocabulary, attribution patterns only)")
    else:
        print("forbidden-terms: clean")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        print(f"forbidden-terms: {error}", file=sys.stderr)
        sys.exit(1)
